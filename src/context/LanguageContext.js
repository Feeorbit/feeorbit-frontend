const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  // Always fixed to English
  const currentLanguage = 'en';

  useEffect(() => {
    if (typeof window === 'undefined') return;

    try {
      // Clear legacy language preferences so the browser is always in English
      localStorage.removeItem('feeorbit_language');
      document.documentElement.lang = 'en';
    } catch (e) {}
  }, []);

  // No-op or lock to English
  const changeLanguage = () => {
    if (typeof window !== 'undefined') {
      try {
        localStorage.removeItem('feeorbit_language');
        document.documentElement.lang = 'en';
      } catch (e) {}
    }
  };

  // Instant Translation helper function (always resolves to English)
  const t = (key, fallback) => {
    if (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined && TRANSLATIONS.en[key] !== '') {
      return TRANSLATIONS.en[key];
    }
    return fallback !== undefined ? fallback : key;
  };

  const activeLangMeta = SUPPORTED_LANGUAGES[0];

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage: 'en',
        changeLanguage,
        t,
        SUPPORTED_LANGUAGES,
        activeLangMeta,
        translations: TRANSLATIONS.en,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      currentLanguage: 'en',
      changeLanguage: () => {},
      t: (key, fallback) => (fallback !== undefined ? fallback : key),
      SUPPORTED_LANGUAGES,
      activeLangMeta: SUPPORTED_LANGUAGES[0],
      translations: TRANSLATIONS.en,
    };
  }
  return context;
}

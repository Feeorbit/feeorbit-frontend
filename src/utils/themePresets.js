export function getThemePreset(presetId) {
  return THEME_PRESETS.find((t) => t.id === presetId) || THEME_PRESETS[0];
}

let isApplyingTheme = false;

export function applyThemeVariables(presetId, customPrimary = null) {
  if (typeof document === 'undefined') return;
  if (isApplyingTheme) return;
  isApplyingTheme = true;

  try {
    const theme = getThemePreset(presetId);
    
    // Resolve primary color:
    // If customPrimary is passed, ONLY use it if it's not the stale default '#6366f1'
    // when switching to non-indigo themes (so emerald is green, crimson is red, obsidian is gold, etc.)
    let primary = theme.primaryColor;
    if (customPrimary && customPrimary !== '#6366f1') {
      primary = customPrimary;
    } else if (customPrimary === '#6366f1' && (theme.id === 'midnight' || theme.id === 'pearl')) {
      primary = '#6366f1';
    }

    const isLight = theme.mode === 'light';
    const root = document.documentElement;

    // Set data-theme and data-theme-mode attributes on <html> element for pure CSS selectors
    root.setAttribute('data-theme', theme.id);
    root.setAttribute('data-theme-mode', theme.mode || (isLight ? 'light' : 'dark'));

    // Set background & card CSS variables on root
    root.style.setProperty('--bg-main', theme.bgMain);
    root.style.setProperty('--bg-sidebar', theme.bgSidebar);
    root.style.setProperty('--bg-card', theme.bgCard);
    root.style.setProperty('--bg-card-solid', theme.bgCardSolid);
    root.style.setProperty('--bg-card-hover', theme.bgCardHover);
    root.style.setProperty('--bg-input', theme.bgInput);
    root.style.setProperty('--border-subtle', theme.borderSubtle);
    root.style.setProperty('--border-hover', theme.borderHover);
    root.style.setProperty('--border-glow', theme.borderGlow);

    // Set typography CSS variables
    root.style.setProperty('--text-primary', theme.textPrimary || (isLight ? '#0f172a' : '#f8fafc'));
    root.style.setProperty('--text-secondary', theme.textSecondary || (isLight ? '#334155' : '#cbd5e1'));
    root.style.setProperty('--text-muted', theme.textMuted || '#94a3b8');

    root.style.setProperty('--brand-primary', primary);
    root.style.setProperty('--brand-primary-hover', theme.primaryHover || primary);
    root.style.setProperty('--brand-primary-glow', theme.primaryGlow || `${primary}55`);
    root.style.setProperty('--brand-primary-light', theme.primaryLight || `${primary}1a`);
    root.style.setProperty('--body-gradient', theme.bodyGradient);

    if (document.body) {
      document.body.style.backgroundColor = theme.bgMain;
      document.body.style.backgroundImage = theme.bodyGradient;
      document.body.style.color = theme.textPrimary || (isLight ? '#0f172a' : '#f8fafc');
    }

    // Save to localStorage
    try {
      localStorage.setItem('feeorbit_theme_preset', theme.id);
      localStorage.setItem('feeorbit_theme_color', primary);
      localStorage.setItem('feeorbit_theme_mode', theme.mode || (isLight ? 'light' : 'dark'));
    } catch (e) {}

    // Broadcast event across components and tabs
    window.dispatchEvent(
      new CustomEvent('feeorbit_theme_changed', {
        detail: { preset: theme.id, primaryColor: primary, theme, mode: theme.mode },
      })
    );
  } finally {
    isApplyingTheme = false;
  }
}
